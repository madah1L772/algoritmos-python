# ejercicio 1: Mostrar la tabla de multiplicar del numero 5
# Definimos el bucle para recorrer los números del 1 al 10
for i in range(1, 11):
    # Realizamos la multiplicación correspondiente
    resultado = 5 * i
    # Imprimimos la operación y su respectivo resultado
    print("5 x", i, "=", resultado)

