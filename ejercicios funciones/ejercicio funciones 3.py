# Función para multiplicar cadenas de texto por un entero
def repetir_texto(texto, veces):
    # En Python, multiplicar un texto por un entero lo repite esa cantidad de veces
    return texto * veces

# Pruebas requeridas
print(repetir_texto("Eco", 3))   # "EcoEcoEco"
print(repetir_texto("Hola", 1))  # "Hola"
print(repetir_texto("Ja", 4))    # "JaJaJaJa"

