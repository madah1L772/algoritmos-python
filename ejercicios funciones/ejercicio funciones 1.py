# Definición de la función que recibe una cadena con el nombre
def saludar(nombre):
    # Retorna el saludo formateado usando f-strings
    return f"Hola, {nombre}!"

# Pruebas requeridas
print(saludar("Carlos"))  # "Hola, Carlos!"
print(saludar("Ana"))     # "Hola, Ana!"
print(saludar("Mundo"))   # "Hola, Mundo!"

