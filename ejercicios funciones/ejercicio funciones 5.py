# Función para obtener la cantidad de caracteres de una cadena
def longitud_nombre(nombre):
    # Usa la función integrada len() para contar las letras
    return len(nombre)

# Pruebas requeridas
print(longitud_nombre("Lucía")) # 5
print(longitud_nombre("Sol"))   # 3
print(longitud_nombre(""))      # 0

